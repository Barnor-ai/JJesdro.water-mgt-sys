  doc.text(`Total Accepted (Good Quality): ${totalAccepted.toLocaleString()}`, 90, startY + 17);
  doc.text(`Total Scrap / Waste: ${totalRejected.toLocaleString()}`, 90, startY + 22);
  doc.text(`Plant Line Yield: ${avgEfficiency.toFixed(2)}%`, 150, startY + 17);

  // Table
