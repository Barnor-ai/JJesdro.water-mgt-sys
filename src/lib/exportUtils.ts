/**
 * Generates customer-branded Financial Statement PDF (Profit & Loss, Balance Sheet, Trial Balance)
 */
export function generateFinancialReportPDF(
  statementTitle: string,
  period: string,
  sections: Array<{
    title: string;
    rows: Array<{ label: string; amount: number; isBold?: boolean }>;
    totalLabel?: string;
    totalAmount?: number;
  }>
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const branding = getCompanyDocumentBranding();
  const startY = renderPdfDocumentHeader(
    doc,
    branding,
    statementTitle,
    `FIN-${new Date().toISOString().slice(0, 10)}`,
    new Date().toISOString()
  );

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`ACCOUNTING PERIOD: ${period.toUpperCase()}`, 15, startY + 6);
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 116, 139);
  doc.text(`Operating Currency: ${branding.currency} (${branding.currencySymbol})`, 15, startY + 11);

  let currentY = startY + 18;

  sections.forEach((sec) => {
    // Section Header
    doc.setFillColor(241, 245, 249);
    doc.rect(15, currentY, 180, 6, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(sec.title.toUpperCase(), 18, currentY + 4.5);
    currentY += 8;

    // Rows
    sec.rows.forEach((r) => {
      doc.setFont('helvetica', r.isBold ? 'bold' : 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(r.isBold ? 15 : 71, r.isBold ? 23 : 85, r.isBold ? 42 : 105);
      doc.text(r.label, 20, currentY);
      doc.text(formatCurrency(r.amount), 190, currentY, { align: 'right' });
      currentY += 6;
    });

    if (sec.totalLabel && sec.totalAmount !== undefined) {
      doc.setDrawColor(203, 213, 225);
      doc.line(15, currentY - 2, 195, currentY - 2);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(2, 132, 199);
      doc.text(sec.totalLabel, 20, currentY + 3);
      doc.text(formatCurrency(sec.totalAmount), 190, currentY + 3, { align: 'right' });
      currentY += 9;
    } else {
      currentY += 3;
    }
  });

  renderPdfDocumentFooter(doc, branding, 260);

  const cleanCompany = branding.companyName.replace(/[^a-zA-Z0-9]/g, '_');
  const safeTitle = statementTitle.replace(/[^a-zA-Z0-9]/g, '_');
  doc.save(`${cleanCompany}_${safeTitle}_${new Date().toISOString().slice(0, 10)}.pdf`);
}

